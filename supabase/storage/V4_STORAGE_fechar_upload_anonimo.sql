-- =============================================================================
-- V4 · STORAGE — FECHA O UPLOAD/REMOÇÃO ANÔNIMOS DO BUCKET  (MANUAL; NÃO é migration; NÃO colocar em supabase/migrations)
--
-- Depois deste script, ninguém grava nem apaga objetos do bucket pets-images com a chave pública (anon/authenticated): a ÚNICA via é a
-- Edge Function imagens-admin (service_role no servidor), que valida o token do Curupira, o papel admin, o caminho, o tipo e o tamanho.
-- A leitura por URL pública do bucket (getPublicUrl) NÃO depende de políticas e continua funcionando.
--
-- PRÉ-REQUISITOS (todos precisam estar cumpridos — o script recusa sem as confirmações):
--   1. Migration 20261029 aplicada e Edge Function "imagens-admin" IMPLANTADA e testada na homologação (upload de pet/acessório/ícone
--      pelo painel admin funcionando com ela).
--   2. App novo publicado (o app antigo faz upload direto e deixa de conseguir enviar imagens depois deste script).
--   3. Rodar antes V4_STORAGE_consultas_pre_pos.sql e guardar a saída.
-- O que faz (uma transação; qualquer falha desfaz tudo):
--   a) registra o retrato das políticas de escrita removidas e da configuração do bucket (public.v4_storage_snapshot; tabela trancada);
--   b) remove as políticas de ESCRITA (INSERT/UPDATE/DELETE/ALL) de storage.objects que valem para anon/authenticated/public e que
--      atingem o bucket (citam o bucket ou não citam bucket nenhum). Políticas restritas a OUTROS buckets não são tocadas;
--   c) define no bucket file_size_limit (2 MB) e allowed_mime_types (png/jpeg/webp/gif) como defesa em profundidade;
--   d) verifica: RLS ligado em storage.objects e nenhuma política de escrita alcançável por anon/authenticated para o bucket.
-- NÃO remove políticas de SELECT (listagem de nomes de arquivo continua possível; imagens já são públicas por design).
-- Rollback: V4_STORAGE_ROLLBACK.sql (REABRE o upload anônimo; exige confirmação + frase).
-- NÃO FOI EXECUTADO NO STORAGE REAL: o teste local usa um esquema "storage" simulado (ver testes/v4_storage_politicas.sh).
-- =============================================================================
BEGIN;
DO $st$
DECLARE
  v_confirmo_edge_function_implantada boolean := false;
  v_confirmo_app_novo_publicado       boolean := false;
  v_bucket text := 'pets-images';
  v_limite_bytes bigint := 2 * 1024 * 1024;
  v_tipos text[] := ARRAY['image/png', 'image/jpeg', 'image/webp', 'image/gif'];
  r record; v_n int := 0; v_ruins text;
BEGIN
  IF NOT (v_confirmo_edge_function_implantada AND v_confirmo_app_novo_publicado) THEN
    RAISE EXCEPTION 'STORAGE RECUSADO: confirme (true) que a Edge Function imagens-admin está implantada e testada e que o app novo está publicado.';
  END IF;
  IF to_regclass('storage.objects') IS NULL OR to_regclass('storage.buckets') IS NULL THEN
    RAISE EXCEPTION 'STORAGE RECUSADO: schema storage ausente.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM storage.buckets WHERE id = v_bucket) THEN
    RAISE EXCEPTION 'STORAGE RECUSADO: bucket % não existe.', v_bucket;
  END IF;
  IF to_regprocedure('public.storage_autorizar_operacao(text,text,text,text)') IS NULL THEN
    RAISE EXCEPTION 'STORAGE RECUSADO: aplique antes a migration 20261029 (storage_autorizar_operacao ausente).';
  END IF;
  IF NOT (SELECT relrowsecurity FROM pg_class WHERE oid = 'storage.objects'::regclass) THEN
    RAISE EXCEPTION 'STORAGE RECUSADO: RLS desligado em storage.objects (não ligue às cegas: revise as políticas com o responsável).';
  END IF;

  -- a) retrato (só definições de política e configuração do bucket; nenhum segredo)
  CREATE TABLE IF NOT EXISTS public.v4_storage_snapshot (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tipo text NOT NULL, nome text, definicao jsonb NOT NULL, em timestamptz NOT NULL DEFAULT now());
  ALTER TABLE public.v4_storage_snapshot ENABLE ROW LEVEL SECURITY;
  REVOKE ALL ON TABLE public.v4_storage_snapshot FROM PUBLIC, anon, authenticated;

  -- b) políticas de escrita alcançáveis por anon/authenticated/public que atingem o bucket
  FOR r IN SELECT p.policyname, p.cmd, p.permissive, p.roles, p.qual, p.with_check
             FROM pg_policies p
            WHERE p.schemaname = 'storage' AND p.tablename = 'objects'
              AND p.cmd IN ('INSERT', 'UPDATE', 'DELETE', 'ALL')
              AND (p.roles && ARRAY['public', 'anon', 'authenticated']::name[])
              AND (COALESCE(p.qual, '') || ' ' || COALESCE(p.with_check, '') ~ ('\m' || v_bucket || '\M')
                   OR COALESCE(p.qual, '') || ' ' || COALESCE(p.with_check, '') !~ 'bucket_id') LOOP
    IF NOT EXISTS (SELECT 1 FROM public.v4_storage_snapshot s WHERE s.tipo = 'politica' AND s.nome = r.policyname) THEN
      INSERT INTO public.v4_storage_snapshot (tipo, nome, definicao)
      VALUES ('politica', r.policyname, jsonb_build_object('cmd', r.cmd, 'permissive', r.permissive, 'roles', r.roles, 'qual', r.qual, 'with_check', r.with_check));
    END IF;
    IF COALESCE(r.qual, '') || ' ' || COALESCE(r.with_check, '') !~ 'bucket_id' THEN
      RAISE NOTICE 'ATENÇÃO: a política GENÉRICA "%" (%) valia para TODOS os buckets e foi removida; se outro bucket dependia dela para gravar, recrie uma política restrita a ele (o retrato permite restaurá-la).', r.policyname, r.cmd;
    END IF;
    EXECUTE format('DROP POLICY %I ON storage.objects', r.policyname);
    v_n := v_n + 1;
  END LOOP;

  -- c) limites do bucket (retrato do valor anterior na 1ª execução)
  IF NOT EXISTS (SELECT 1 FROM public.v4_storage_snapshot WHERE tipo = 'bucket') THEN
    INSERT INTO public.v4_storage_snapshot (tipo, nome, definicao)
    SELECT 'bucket', b.id, jsonb_build_object('file_size_limit', b.file_size_limit, 'allowed_mime_types', b.allowed_mime_types) FROM storage.buckets b WHERE b.id = v_bucket;
  END IF;
  UPDATE storage.buckets SET file_size_limit = v_limite_bytes, allowed_mime_types = v_tipos WHERE id = v_bucket;

  -- d) verificação: nenhuma política de escrita restante alcança o bucket para esses papéis
  SELECT string_agg(p.policyname, ', ') INTO v_ruins FROM pg_policies p
   WHERE p.schemaname = 'storage' AND p.tablename = 'objects' AND p.cmd IN ('INSERT', 'UPDATE', 'DELETE', 'ALL')
     AND (p.roles && ARRAY['public', 'anon', 'authenticated']::name[])
     AND (COALESCE(p.qual, '') || ' ' || COALESCE(p.with_check, '') ~ ('\m' || v_bucket || '\M')
          OR COALESCE(p.qual, '') || ' ' || COALESCE(p.with_check, '') !~ 'bucket_id');
  IF v_ruins IS NOT NULL THEN RAISE EXCEPTION 'VERIFICAÇÃO FALHOU: políticas de escrita ainda alcançam o bucket: %', v_ruins; END IF;
  RAISE NOTICE 'Storage: % política(s) de escrita removida(s); bucket com limite de % bytes e tipos %.', v_n, v_limite_bytes, v_tipos;
END
$st$;
COMMIT;
