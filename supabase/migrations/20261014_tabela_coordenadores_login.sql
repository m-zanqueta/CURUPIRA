-- Armazena os logins de coordenador fora da tabela de professores.
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;

CREATE TABLE IF NOT EXISTS public.coordenadores (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  email text NOT NULL UNIQUE,
  senha_hash text NOT NULL,
  ativo boolean NOT NULL DEFAULT true,
  criado_em timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.coordenadores ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.coordenadores FROM PUBLIC, anon, authenticated;

INSERT INTO public.coordenadores (nome, email, senha_hash, ativo)
VALUES (
  'Coordenador',
  'coordenador@email.com',
  extensions.crypt('Coordenador123!', extensions.gen_salt('bf')),
  true
)
ON CONFLICT (email) DO UPDATE
SET nome = EXCLUDED.nome,
    senha_hash = EXCLUDED.senha_hash,
    ativo = true;

-- A senha é verificada no banco; a tabela e o hash não são expostos ao app.
CREATE OR REPLACE FUNCTION public.login_coordenador(p_email text, p_senha text)
RETURNS TABLE (id bigint, nome text, email text, tipo text)
LANGUAGE sql
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT c.id, c.nome, c.email, 'coordenador'::text
  FROM public.coordenadores AS c
  WHERE lower(c.email) = lower(trim(p_email))
    AND c.ativo = true
    AND c.senha_hash = extensions.crypt(p_senha, c.senha_hash)
  LIMIT 1;
$$;

REVOKE ALL ON FUNCTION public.login_coordenador(text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.login_coordenador(text, text) TO anon, authenticated;

-- Remove o registro de teste que a migração anterior guardou em professores.
DELETE FROM public.professores
WHERE lower(email) = 'coordenador@email.com';

NOTIFY pgrst, 'reload schema';
