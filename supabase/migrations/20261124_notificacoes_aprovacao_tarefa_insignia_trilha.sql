-- Aprovacoes de tarefas geram aviso privado para o aluno. O bonus da trilha
-- continua sendo entregue depois da aprovacao da coordenacao.
CREATE TABLE IF NOT EXISTS public.alunos_tarefas_notificacoes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aluno_id bigint NOT NULL REFERENCES public.alunos(id) ON DELETE CASCADE,
  envio_id bigint NOT NULL REFERENCES public.alunos_missoes_etapas(id) ON DELETE CASCADE,
  missao_id bigint NOT NULL REFERENCES public.missoes(id) ON DELETE CASCADE,
  tarefa_titulo text NOT NULL,
  missao_titulo text NOT NULL,
  moedas bigint NOT NULL DEFAULT 0 CHECK (moedas >= 0),
  criado_em timestamptz NOT NULL DEFAULT now(),
  exibida_em timestamptz,
  CONSTRAINT alunos_tarefas_notificacoes_envio_unica UNIQUE (envio_id)
);
CREATE INDEX IF NOT EXISTS alunos_tarefas_notificacoes_pendente_idx
  ON public.alunos_tarefas_notificacoes(aluno_id,id) WHERE exibida_em IS NULL;
ALTER TABLE public.alunos_tarefas_notificacoes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.alunos_tarefas_notificacoes FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION public.staff_revisar_envio_tarefa(p_token text,p_envio_id bigint,p_aprovado boolean)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_papel text;
  v_id bigint;
  v_e public.alunos_missoes_etapas%ROWTYPE;
  v_valor bigint;
  v_n integer;
  v_titulo text;
  v_missao text;
BEGIN
  SELECT s.papel,s.usuario_id INTO v_papel,v_id
  FROM public._staff_exigir(p_token,ARRAY['professor','admin']) s;
  SELECT e.* INTO v_e FROM public.alunos_missoes_etapas e WHERE e.id=p_envio_id FOR UPDATE;
  IF NOT FOUND OR v_e.status<>'enviado' OR v_e.evidencia_path IS NULL THEN
    RAISE EXCEPTION 'envio_nao_encontrado' USING ERRCODE='PT404';
  END IF;
  IF v_papel='professor' AND NOT EXISTS (
    SELECT 1 FROM public.turmas t WHERE t.id=v_e.turma_id AND t.professor_id=v_id
  ) THEN RAISE EXCEPTION 'sem_permissao' USING ERRCODE='PT403'; END IF;

  IF p_aprovado THEN
    SELECT COALESCE((m.etapas->(v_e.etapa_ordem-1)->>'moedas')::bigint,0),
           COALESCE(m.etapas->(v_e.etapa_ordem-1)->>'titulo','Tarefa '||v_e.etapa_ordem::text),m.nome
      INTO v_valor,v_titulo,v_missao
      FROM public.missoes m WHERE m.id=v_e.missao_id;
    UPDATE public.alunos_missoes_etapas
      SET status='aprovado',moedas=v_valor,evidencia_path=NULL,corrigida_em=now()
      WHERE id=v_e.id;
    UPDATE public.alunos_missoes
      SET etapa_atual=v_e.etapa_ordem,atualizado_em=now()
      WHERE aluno_id=v_e.aluno_id AND missao_id=v_e.missao_id AND etapa_atual=v_e.etapa_ordem-1;
    GET DIAGNOSTICS v_n=ROW_COUNT;
    IF v_n=0 THEN RAISE EXCEPTION 'etapa_fora_de_ordem' USING ERRCODE='PT409'; END IF;

    INSERT INTO public.alunos_tarefas_notificacoes(aluno_id,envio_id,missao_id,tarefa_titulo,missao_titulo,moedas)
    VALUES(v_e.aluno_id,v_e.id,v_e.missao_id,v_titulo,v_missao,v_valor)
    ON CONFLICT(envio_id) DO NOTHING;
  ELSE
    UPDATE public.alunos_missoes_etapas
      SET status='recusado',evidencia_path=NULL,corrigida_em=now() WHERE id=v_e.id;
  END IF;
  -- Registra o descarte na mesma transacao que apaga o caminho da linha, para
  -- que a fila sobreviva ate mesmo se a chamada da Edge Function cair depois.
  IF v_e.evidencia_path IS NOT NULL THEN
    INSERT INTO public.tarefas_evidencias_lixeira(caminho) VALUES(v_e.evidencia_path)
    ON CONFLICT(caminho) DO NOTHING;
  END IF;
  RETURN jsonb_build_object('ok',true,'caminho',v_e.evidencia_path,
    'status',CASE WHEN p_aprovado THEN 'aprovado' ELSE 'recusado' END);
END;
$$;
REVOKE ALL ON FUNCTION public.staff_revisar_envio_tarefa(text,bigint,boolean) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.staff_revisar_envio_tarefa(text,bigint,boolean) TO service_role;

CREATE OR REPLACE FUNCTION public.aluno_notificacoes_tarefas(p_token text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_aluno bigint:=public._aluno_da_sessao(p_token); v_resultado jsonb;
BEGIN
  SELECT COALESCE(jsonb_agg(jsonb_build_object(
    'id',n.id,'missao_id',n.missao_id,'titulo',n.tarefa_titulo,'missao_titulo',n.missao_titulo,'icone','✅',
    'moedas',n.moedas,'mensagem','Seu professor aprovou a tarefa! Você ganhou +'||n.moedas||' moedas.',
    'criado_em',n.criado_em
  ) ORDER BY n.id),'[]'::jsonb)
  INTO v_resultado
  FROM (SELECT * FROM public.alunos_tarefas_notificacoes
        WHERE aluno_id=v_aluno AND exibida_em IS NULL ORDER BY id LIMIT 10) n;
  RETURN v_resultado;
END;
$$;

CREATE OR REPLACE FUNCTION public.aluno_marcar_notificacao_tarefa(p_token text,p_notificacao_id bigint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_aluno bigint:=public._aluno_da_sessao(p_token);
BEGIN
  UPDATE public.alunos_tarefas_notificacoes SET exibida_em=now()
  WHERE id=p_notificacao_id AND aluno_id=v_aluno AND exibida_em IS NULL;
END;
$$;
REVOKE ALL ON FUNCTION public.aluno_notificacoes_tarefas(text),public.aluno_marcar_notificacao_tarefa(text,bigint) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.aluno_notificacoes_tarefas(text),public.aluno_marcar_notificacao_tarefa(text,bigint) TO anon,authenticated;

-- A insígnia fica disponível assim que todas as tarefas da trilha foram
-- aprovadas pelo professor, sem esperar a avaliação final da coordenação.
CREATE OR REPLACE FUNCTION public.aluno_vitrine_listar(p_token text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_aluno bigint:=public._aluno_da_sessao(p_token); v_resultado jsonb;
BEGIN
  SELECT COALESCE(jsonb_agg(jsonb_build_object('id',m.id,'nome',m.nome,'icone',m.icone,'posicao',v.posicao)
    ORDER BY v.posicao NULLS LAST,m.id),'[]'::jsonb) INTO v_resultado
  FROM public.alunos_missoes am JOIN public.missoes m ON m.id=am.missao_id
  LEFT JOIN public.alunos_vitrine_trilhas v ON v.aluno_id=v_aluno AND v.missao_id=m.id
  WHERE am.aluno_id=v_aluno AND (
    am.status='aprovado' OR
    CASE WHEN jsonb_typeof(m.etapas)='array'
      THEN jsonb_array_length(m.etapas)>0 AND am.etapa_atual>=jsonb_array_length(m.etapas)
      ELSE false END
  );
  RETURN v_resultado;
END;
$$;

CREATE OR REPLACE FUNCTION public.aluno_vitrine_salvar(p_token text,p_missoes_ids bigint[])
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_aluno bigint:=public._aluno_da_sessao(p_token); v_ids bigint[]:=COALESCE(p_missoes_ids,ARRAY[]::bigint[]);
BEGIN
  IF cardinality(v_ids)>5 OR (SELECT count(DISTINCT u.missao_id) FROM unnest(v_ids) AS u(missao_id))<>cardinality(v_ids) THEN
    RAISE EXCEPTION 'vitrine_invalida' USING ERRCODE='PT422';
  END IF;
  IF EXISTS(SELECT 1 FROM unnest(v_ids) AS u(missao_id) WHERE u.missao_id IS NULL OR NOT EXISTS(
    SELECT 1 FROM public.alunos_missoes am JOIN public.missoes m ON m.id=am.missao_id
    WHERE am.aluno_id=v_aluno AND am.missao_id=u.missao_id AND (
      am.status='aprovado' OR
      CASE WHEN jsonb_typeof(m.etapas)='array'
        THEN jsonb_array_length(m.etapas)>0 AND am.etapa_atual>=jsonb_array_length(m.etapas)
        ELSE false END
    )
  )) THEN RAISE EXCEPTION 'insignia_nao_conquistada' USING ERRCODE='PT403'; END IF;
  DELETE FROM public.alunos_vitrine_trilhas WHERE aluno_id=v_aluno;
  INSERT INTO public.alunos_vitrine_trilhas(aluno_id,missao_id,posicao)
  SELECT v_aluno,u.missao_id,u.ordem::smallint FROM unnest(v_ids) WITH ORDINALITY AS u(missao_id,ordem);
END;
$$;
REVOKE ALL ON FUNCTION public.aluno_vitrine_listar(text),public.aluno_vitrine_salvar(text,bigint[]) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.aluno_vitrine_listar(text),public.aluno_vitrine_salvar(text,bigint[]) TO anon,authenticated;

-- A entrega da trilha só pode ser registrada depois que todos os passos foram
-- confirmados pelo professor; a validação também é aplicada no servidor.
CREATE OR REPLACE FUNCTION public.aluno_definir_status_missao(p_token text,p_missao_id bigint,p_status text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_aluno bigint:=public._aluno_da_sessao(p_token); v_atual text; v_resultado jsonb;
BEGIN
  IF p_status IS NULL OR p_status NOT IN ('pendente','entregue') THEN
    RAISE EXCEPTION 'status_invalido' USING ERRCODE='PT422';
  END IF;
  IF NOT EXISTS(SELECT 1 FROM public.missoes WHERE id=p_missao_id) THEN
    RAISE EXCEPTION 'nao_encontrado' USING ERRCODE='PT404';
  END IF;
  SELECT status INTO v_atual FROM public.alunos_missoes
  WHERE aluno_id=v_aluno AND missao_id=p_missao_id FOR UPDATE;
  IF v_atual='aprovado' OR (v_atual='entregue' AND p_status='pendente') THEN
    RAISE EXCEPTION 'transicao_invalida' USING ERRCODE='PT409';
  END IF;
  IF p_status='entregue' AND NOT EXISTS(
    SELECT 1 FROM public.alunos_missoes am JOIN public.missoes m ON m.id=am.missao_id
    WHERE am.aluno_id=v_aluno AND am.missao_id=p_missao_id
      AND CASE WHEN jsonb_typeof(m.etapas)='array'
        THEN jsonb_array_length(m.etapas)>0 AND am.etapa_atual>=jsonb_array_length(m.etapas)
        ELSE false END
  ) THEN RAISE EXCEPTION 'trilha_incompleta' USING ERRCODE='PT409'; END IF;

  LOOP
    UPDATE public.alunos_missoes am SET status=p_status
    WHERE am.aluno_id=v_aluno AND am.missao_id=p_missao_id
    RETURNING to_jsonb(am.*) INTO v_resultado;
    EXIT WHEN FOUND;
    BEGIN
      INSERT INTO public.alunos_missoes AS am(missao_id,aluno_id,status)
      VALUES(p_missao_id,v_aluno,p_status) RETURNING to_jsonb(am.*) INTO v_resultado;
      EXIT;
    EXCEPTION WHEN unique_violation THEN NULL;
    END;
  END LOOP;
  RETURN v_resultado;
END;
$$;
REVOKE ALL ON FUNCTION public.aluno_definir_status_missao(text,bigint,text) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.aluno_definir_status_missao(text,bigint,text) TO anon,authenticated;

