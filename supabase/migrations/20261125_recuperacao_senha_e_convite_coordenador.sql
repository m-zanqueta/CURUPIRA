-- Corrige a RPC de troca do PET caso a migration inicial ainda não exista no projeto remoto.
CREATE OR REPLACE FUNCTION public.staff_atribuir_pet_turma(p_token text,p_turma_id bigint,p_pet_id bigint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  PERFORM public._staff_exigir(p_token,ARRAY['coordenador']);
  PERFORM 1 FROM public.turmas WHERE id=p_turma_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'nao_encontrado' USING ERRCODE='PT404'; END IF;
  PERFORM 1 FROM public.pets WHERE id=p_pet_id AND (turma_id IS NULL OR turma_id=p_turma_id) FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'pet_indisponivel' USING ERRCODE='PT409'; END IF;
  UPDATE public.pets SET turma_id=NULL WHERE turma_id=p_turma_id AND id<>p_pet_id;
  UPDATE public.pets SET turma_id=p_turma_id WHERE id=p_pet_id;
END;
$$;
REVOKE ALL ON FUNCTION public.staff_atribuir_pet_turma(text,bigint,bigint) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.staff_atribuir_pet_turma(text,bigint,bigint) TO anon,authenticated;

-- O convite usa o endereço do coordenador como reply-to; o remetente continua
-- sendo o domínio autenticado no SendGrid.
CREATE OR REPLACE FUNCTION public.coordenador_identidade_convite(p_token text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_id bigint; v_resultado jsonb;
BEGIN
  SELECT s.usuario_id INTO v_id FROM public._staff_exigir(p_token,ARRAY['coordenador']) s;
  SELECT jsonb_build_object('nome',c.nome,'email',lower(c.email)) INTO v_resultado
  FROM public.coordenadores c WHERE c.id=v_id AND c.ativo;
  IF v_resultado IS NULL THEN RAISE EXCEPTION 'sessao_invalida' USING ERRCODE='PT401'; END IF;
  RETURN v_resultado;
END;
$$;
REVOKE ALL ON FUNCTION public.coordenador_identidade_convite(text) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.coordenador_identidade_convite(text) TO service_role;

-- Códigos de recuperação: segredo aleatório guardado somente como HMAC, prazo
-- de 10 min, uso único e limite de tentativas. RLS e grants de clientes fechados.
CREATE TABLE IF NOT EXISTS public.recuperacao_senhas_codigos(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL,
  papel text NOT NULL CHECK(papel IN ('aluno','staff')),
  tipo_conta text NOT NULL CHECK(tipo_conta IN ('aluno','professor','coordenador','admin')),
  usuario_id bigint NOT NULL,
  codigo_hash text NOT NULL CHECK(codigo_hash ~ '^[a-f0-9]{64}$'),
  criado_em timestamptz NOT NULL DEFAULT now(),
  expira_em timestamptz NOT NULL DEFAULT now()+interval '10 minutes',
  tentativas smallint NOT NULL DEFAULT 0 CHECK(tentativas BETWEEN 0 AND 5),
  usado_em timestamptz
);
CREATE INDEX IF NOT EXISTS recuperacao_senhas_codigos_email_idx
  ON public.recuperacao_senhas_codigos(papel,email,criado_em DESC);
CREATE TABLE IF NOT EXISTS public.recuperacao_senhas_eventos(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email_hash text NOT NULL,
  ip_hash text NOT NULL,
  criado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS recuperacao_senhas_eventos_email_idx ON public.recuperacao_senhas_eventos(email_hash,criado_em);
CREATE INDEX IF NOT EXISTS recuperacao_senhas_eventos_ip_idx ON public.recuperacao_senhas_eventos(ip_hash,criado_em);
ALTER TABLE public.recuperacao_senhas_codigos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.recuperacao_senhas_eventos ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.recuperacao_senhas_codigos,public.recuperacao_senhas_eventos FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.recuperacao_senhas_codigos,public.recuperacao_senhas_eventos TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.recuperacao_senhas_codigos_id_seq,public.recuperacao_senhas_eventos_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.recuperacao_senha_iniciar(p_email text,p_papel text,p_codigo_hash text,p_ip_hash text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_email text:=lower(btrim(coalesce(p_email,''))); v_usuario bigint; v_tipo text; v_hash_email text;
BEGIN
  IF v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]{2,}$' OR p_papel NOT IN ('aluno','staff')
     OR p_codigo_hash !~ '^[a-f0-9]{64}$' OR p_ip_hash !~ '^[a-f0-9]{64}$' THEN
    RAISE EXCEPTION 'pedido_invalido' USING ERRCODE='PT422';
  END IF;
  v_hash_email:=encode(extensions.digest(v_email,'sha256'),'hex');
  PERFORM pg_advisory_xact_lock(hashtextextended('recuperacao:'||v_hash_email,0));
  DELETE FROM public.recuperacao_senhas_codigos WHERE criado_em<now()-interval '1 day';
  DELETE FROM public.recuperacao_senhas_eventos WHERE criado_em<now()-interval '1 day';
  IF (SELECT count(*) FROM public.recuperacao_senhas_eventos WHERE email_hash=v_hash_email AND criado_em>now()-interval '1 hour')>=3
     OR (SELECT count(*) FROM public.recuperacao_senhas_eventos WHERE ip_hash=p_ip_hash AND criado_em>now()-interval '1 hour')>=20 THEN
    RAISE EXCEPTION 'muitas_tentativas' USING ERRCODE='PT429';
  END IF;
  INSERT INTO public.recuperacao_senhas_eventos(email_hash,ip_hash) VALUES(v_hash_email,p_ip_hash);

  IF p_papel='aluno' THEN
    SELECT a.id INTO v_usuario FROM public.alunos a JOIN public.alunos_credenciais c ON c.aluno_id=a.id
    WHERE lower(a.email)=v_email ORDER BY a.id LIMIT 1;
    IF v_usuario IS NOT NULL THEN v_tipo:='aluno'; END IF;
  ELSE
    SELECT c.id INTO v_usuario FROM public.coordenadores c WHERE lower(c.email)=v_email AND c.ativo LIMIT 1;
    IF v_usuario IS NOT NULL THEN v_tipo:='coordenador'; END IF;
    IF v_usuario IS NULL THEN SELECT a.id INTO v_usuario FROM public.administradores a WHERE lower(a.email)=v_email AND a.ativo LIMIT 1;
      IF v_usuario IS NOT NULL THEN v_tipo:='admin'; END IF;
    END IF;
    IF v_usuario IS NULL THEN SELECT p.id INTO v_usuario FROM public.professores p JOIN public.professores_credenciais c ON c.professor_id=p.id
      WHERE lower(p.email)=v_email AND coalesce(p.tipo,'professor')='professor' ORDER BY p.id LIMIT 1;
      IF v_usuario IS NOT NULL THEN v_tipo:='professor'; END IF;
    END IF;
  END IF;
  IF v_usuario IS NULL THEN RETURN jsonb_build_object('enviar',false); END IF;
  DELETE FROM public.recuperacao_senhas_codigos WHERE email=v_email AND papel=p_papel AND usado_em IS NULL;
  INSERT INTO public.recuperacao_senhas_codigos(email,papel,tipo_conta,usuario_id,codigo_hash)
  VALUES(v_email,p_papel,v_tipo,v_usuario,p_codigo_hash);
  RETURN jsonb_build_object('enviar',true);
END;
$$;

CREATE OR REPLACE FUNCTION public.recuperacao_senha_cancelar(p_email text,p_papel text)
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = '' AS $$
  DELETE FROM public.recuperacao_senhas_codigos WHERE email=lower(btrim(p_email)) AND papel=p_papel AND usado_em IS NULL
$$;

CREATE OR REPLACE FUNCTION public.recuperacao_senha_confirmar(p_email text,p_papel text,p_codigo_hash text,p_senha_nova text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_email text:=lower(btrim(coalesce(p_email,''))); v_c public.recuperacao_senhas_codigos%ROWTYPE;
BEGIN
  IF p_papel NOT IN ('aluno','staff') OR p_codigo_hash !~ '^[a-f0-9]{64}$'
     OR NOT public._senha_forte(p_senha_nova,true) THEN
    RAISE EXCEPTION 'dados_invalidos' USING ERRCODE='PT422';
  END IF;
  SELECT * INTO v_c FROM public.recuperacao_senhas_codigos c
  WHERE c.email=v_email AND c.papel=p_papel AND c.usado_em IS NULL
    AND c.expira_em>now() AND c.tentativas<5
  ORDER BY c.id DESC LIMIT 1 FOR UPDATE;
  IF NOT FOUND THEN RETURN jsonb_build_object('ok',false); END IF;
  IF v_c.codigo_hash<>p_codigo_hash THEN
    UPDATE public.recuperacao_senhas_codigos SET tentativas=least(tentativas+1,5) WHERE id=v_c.id;
    RETURN jsonb_build_object('ok',false);
  END IF;

  IF p_papel='aluno' THEN
    UPDATE public.alunos SET senha=p_senha_nova WHERE id=v_c.usuario_id AND lower(email)=v_email;
    IF NOT FOUND THEN RETURN jsonb_build_object('ok',false); END IF;
    UPDATE public.alunos_sessoes SET revogado_em=now() WHERE aluno_id=v_c.usuario_id AND revogado_em IS NULL;
  ELSIF v_c.tipo_conta='coordenador' THEN
      UPDATE public.coordenadores SET senha_hash=extensions.crypt(p_senha_nova,extensions.gen_salt('bf',10)) WHERE id=v_c.usuario_id;
      IF NOT FOUND THEN RETURN jsonb_build_object('ok',false); END IF;
    ELSIF v_c.tipo_conta='admin' THEN
      UPDATE public.administradores SET senha_hash=extensions.crypt(p_senha_nova,extensions.gen_salt('bf',10)) WHERE id=v_c.usuario_id;
      IF NOT FOUND THEN RETURN jsonb_build_object('ok',false); END IF;
    ELSIF v_c.tipo_conta='professor' THEN
      UPDATE public.professores SET senha=p_senha_nova WHERE id=v_c.usuario_id AND lower(email)=v_email;
      IF NOT FOUND THEN RETURN jsonb_build_object('ok',false); END IF;
      UPDATE public.professores_credenciais SET deve_trocar_senha=false,senha_hash=extensions.crypt(p_senha_nova,extensions.gen_salt('bf',10)),atualizado_em=now()
      WHERE professor_id=v_c.usuario_id;
    ELSE RETURN jsonb_build_object('ok',false);
  END IF;
  IF v_c.tipo_conta<>'aluno' THEN
    UPDATE public.staff_sessoes SET revogado_em=now() WHERE usuario_id=v_c.usuario_id AND papel=v_c.tipo_conta AND revogado_em IS NULL;
  END IF;
  UPDATE public.recuperacao_senhas_codigos SET usado_em=now() WHERE id=v_c.id;
  DELETE FROM public.recuperacao_senhas_codigos WHERE email=v_email AND papel=p_papel AND id<>v_c.id;
  RETURN jsonb_build_object('ok',true);
END;
$$;

REVOKE ALL ON FUNCTION public.recuperacao_senha_iniciar(text,text,text,text),public.recuperacao_senha_cancelar(text,text),
  public.recuperacao_senha_confirmar(text,text,text,text) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.recuperacao_senha_iniciar(text,text,text,text),public.recuperacao_senha_cancelar(text,text),
  public.recuperacao_senha_confirmar(text,text,text,text) TO service_role;

NOTIFY pgrst,'reload schema';
