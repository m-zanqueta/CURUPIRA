-- Reverte, uma única vez, XP que a primeira versão possa ter creditado por conquistas.
DO $$
DECLARE c record; v_turma bigint; v_pet bigint;
BEGIN
  FOR c IN SELECT id, "alunoId" AS aluno_id, COALESCE(xp,0) AS xp FROM public.conquistas
            WHERE xp_creditado AND NOT xp_revertido FOR UPDATE LOOP
    SELECT a."turmaId" INTO v_turma FROM public.alunos a WHERE a.id=c.aluno_id;
    SELECT p.id INTO v_pet FROM public.pets p WHERE p.turma_id=v_turma ORDER BY p.id LIMIT 1;
    IF c.xp > 0 THEN
      UPDATE public.alunos SET xp=GREATEST(COALESCE(xp,0)-c.xp,0) WHERE id=c.aluno_id;
      IF v_pet IS NOT NULL THEN UPDATE public.pets SET xp=GREATEST(COALESCE(xp,0)-c.xp,0) WHERE id=v_pet; END IF;
    END IF;
    UPDATE public.conquistas SET xp=0,xp_creditado=false,xp_revertido=true WHERE id=c.id;
  END LOOP;
END $$;
UPDATE public.conquistas SET xp=0 WHERE regra_id IS NOT NULL AND COALESCE(xp,0) <> 0;

