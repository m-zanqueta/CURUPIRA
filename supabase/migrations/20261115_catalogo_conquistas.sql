END; $$;

CREATE OR REPLACE FUNCTION public.aluno_minhas_conquistas(p_token text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_aluno bigint := public._aluno_da_sessao(p_token); v_r jsonb;
BEGIN
  PERFORM public._conquistas_avaliar_aluno(v_aluno);
  SELECT COALESCE(jsonb_agg(jsonb_build_object(
    'id',r.codigo,'regra_id',r.id,'titulo',r.titulo,'descricao',r.descricao,'icone',r.icone,'raridade',r.raridade,
    'desbloqueada',c.id IS NOT NULL,'conquistada_em',c.conquistada_em) ORDER BY r.id), '[]'::jsonb)
    INTO v_r FROM public.regras_conquistas r LEFT JOIN public.conquistas c
      ON c.regra_id=r.id AND c."alunoId"=v_aluno WHERE r.ativa;
  RETURN v_r;
END; $$;

CREATE OR REPLACE FUNCTION public.aluno_meu_progresso_geral(p_token text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_aluno bigint := public._aluno_da_sessao(p_token);
BEGIN
  RETURN jsonb_build_object(
    'missoesAprovadas',(SELECT count(*) FROM public.alunos_missoes am WHERE am.aluno_id=v_aluno AND am.status='aprovado'),
    'conquistas',(SELECT count(*) FROM public.conquistas c JOIN public.regras_conquistas r ON r.id=c.regra_id
                   WHERE c."alunoId"=v_aluno AND r.ativa)
  );
END; $$;

