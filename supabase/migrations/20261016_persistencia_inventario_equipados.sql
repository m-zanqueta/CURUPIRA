-- Resolve o aluno pelo token. Nunca aceita p_aluno do cliente.
CREATE OR REPLACE FUNCTION public._aluno_da_sessao(p_token text)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE v_aluno bigint;
BEGIN
  IF p_token IS NULL OR length(p_token) < 32 THEN
    RAISE EXCEPTION 'sessao_invalida' USING ERRCODE = 'PT401';
  END IF;
  SELECT s.aluno_id INTO v_aluno
  FROM public.alunos_sessoes s
  WHERE s.token_hash = extensions.digest(p_token, 'sha256')
    AND s.revogado_em IS NULL
    AND s.expira_em > now();
  IF v_aluno IS NULL THEN
    RAISE EXCEPTION 'sessao_invalida' USING ERRCODE = 'PT401';
  END IF;
  RETURN v_aluno;
END;
$$;
REVOKE ALL ON FUNCTION public._aluno_da_sessao(text) FROM PUBLIC, anon, authenticated;

-- Saldo = xp do aluno - soma do que ele pagou. O chamador deve ter travado a
-- linha do aluno (FOR UPDATE) quando for decidir uma compra.
CREATE OR REPLACE FUNCTION public._saldo_aluno(p_aluno bigint)
RETURNS bigint
LANGUAGE sql
STABLE
SET search_path = ''
AS $$
  SELECT COALESCE((SELECT a.xp FROM public.alunos a WHERE a.id = p_aluno), 0)::bigint
       - COALESCE((SELECT sum(i.preco_pago) FROM public.alunos_itens i WHERE i.aluno_id = p_aluno), 0)::bigint;
$$;
REVOKE ALL ON FUNCTION public._saldo_aluno(bigint) FROM PUBLIC, anon, authenticated;

-- -----------------------------------------------------------------------------
-- 6) RPCs públicas (chamadas pelo app com a chave anon + token de sessão)
-- -----------------------------------------------------------------------------
-- Limite de tentativas (janela de 15 min), em três camadas:
--   * 5 falhas por (e-mail + IP): para força bruta a partir de um mesmo cliente;
--   * 30 falhas por e-mail (qualquer IP): teto contra rotação de IPs;
--   * 60 falhas por IP (qualquer e-mail): contra "password spraying".
-- As tentativas do mesmo e-mail são serializadas (advisory lock); o teto por IP é "melhor esforço" sob paralelismo.
-- Estourou => PT429 (HTTP 429). O IP vem de request.headers (x-forwarded-for /
-- x-real-ip) e PODE ser forjado pelo cliente dependendo do proxy; por isso a
-- camada por e-mail existe. Limite conhecido: um atacante determinado ainda
-- consegue travar um e-mail (30 falhas/15 min) — só CAPTCHA/limite na borda
-- resolve de vez. Um bcrypt é sempre calculado (mesmo e-mail inexistente) para
-- não revelar, pelo tempo de resposta, se o e-mail existe.
CREATE OR REPLACE FUNCTION public.login_aluno(p_email text, p_senha text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_email text := left(lower(trim(COALESCE(p_email, ''))), 254);
  v_senha text := left(COALESCE(p_senha, ''), 1000);
  v_hdr   json;
  v_ip    text;
  v_aluno public.alunos%ROWTYPE;
  v_hash  text;
  v_ok    boolean := false;
  v_gastou boolean := false;   -- já rodou um bcrypt (tempo de resposta uniforme)
  v_token text;
BEGIN
  BEGIN
    v_hdr := current_setting('request.headers', true)::json;
  EXCEPTION WHEN OTHERS THEN v_hdr := NULL;
  END;
  v_ip := left(COALESCE(
            NULLIF(trim(split_part(COALESCE(v_hdr->>'x-forwarded-for', ''), ',', 1)), ''),
            NULLIF(trim(COALESCE(v_hdr->>'x-real-ip', '')), ''),
            'desconhecido'), 64);

  -- Serializa as tentativas do MESMO e-mail (lock até o fim da transação). Sem isso, N tentativas em
  -- paralelo leem o contador antes de qualquer falha ser gravada e passam todas do limite (comprovado nos
  -- testes: 30 requisições paralelas => 11 verificações de senha em vez de 5).
  PERFORM pg_advisory_xact_lock(hashtextextended('login_aluno:' || v_email, 0));

  -- Limpeza oportunista (tabelas pequenas, indexadas).
  DELETE FROM public.alunos_login_falhas WHERE ocorrido_em < now() - interval '1 day';
  DELETE FROM public.alunos_sessoes
   WHERE expira_em < now() - interval '30 days' OR revogado_em < now() - interval '30 days';

  IF (SELECT count(*) FROM public.alunos_login_falhas
        WHERE email = v_email AND ip IS NOT DISTINCT FROM v_ip
          AND ocorrido_em > now() - interval '15 minutes') >= 5
     OR (SELECT count(*) FROM public.alunos_login_falhas
           WHERE email = v_email AND ocorrido_em > now() - interval '15 minutes') >= 30
     OR (SELECT count(*) FROM public.alunos_login_falhas
           WHERE ip IS NOT DISTINCT FROM v_ip AND ocorrido_em > now() - interval '15 minutes') >= 60
  THEN
    RAISE EXCEPTION 'muitas_tentativas' USING ERRCODE = 'PT429';
  END IF;

  -- e-mails duplicados (não há UNIQUE garantido): confere cada conta, em ordem de id
  FOR v_aluno IN
    SELECT * FROM public.alunos a WHERE lower(a.email) = v_email ORDER BY a.id LIMIT 5
  LOOP
    IF v_senha <> '' THEN
      SELECT c.senha_hash INTO v_hash FROM public.alunos_credenciais c WHERE c.aluno_id = v_aluno.id;
      IF v_hash IS NOT NULL THEN
        v_ok := v_hash = extensions.crypt(v_senha, v_hash);
        v_gastou := true;
      ELSIF v_aluno.senha IS NOT NULL AND v_aluno.senha <> '' AND v_aluno.senha = v_senha THEN
        v_ok := true;  -- transição: 1º login com senha em texto puro => cria o hash
        v_gastou := true;
        INSERT INTO public.alunos_credenciais (aluno_id, senha_hash)
        VALUES (v_aluno.id, extensions.crypt(v_senha, extensions.gen_salt('bf', 10)))
        ON CONFLICT (aluno_id) DO NOTHING;
      END IF;
    END IF;
    EXIT WHEN v_ok;
  END LOOP;

  IF NOT v_gastou THEN
    PERFORM extensions.crypt(v_senha, extensions.gen_salt('bf', 10));  -- e-mail inexistente / conta em transição: mesmo custo
  END IF;

  IF NOT v_ok THEN
    INSERT INTO public.alunos_login_falhas (email, ip) VALUES (v_email, v_ip);
    RETURN NULL;  -- mesmo retorno para e-mail inexistente e senha errada
  END IF;

  DELETE FROM public.alunos_login_falhas WHERE email = v_email AND ip IS NOT DISTINCT FROM v_ip;

  v_token := encode(extensions.gen_random_bytes(32), 'hex');   -- 256 bits
  INSERT INTO public.alunos_sessoes (aluno_id, token_hash)
  VALUES (v_aluno.id, extensions.digest(v_token, 'sha256'));   -- só o hash fica no banco

  RETURN jsonb_build_object(
    'token', v_token,
    'aluno', to_jsonb(v_aluno) - 'senha' - 'senha_hash'
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.logout_aluno(p_token text)
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = ''
AS $$
  UPDATE public.alunos_sessoes
  SET revogado_em = now()
  WHERE token_hash = extensions.digest(COALESCE(p_token, ''), 'sha256')
    AND revogado_em IS NULL;
$$;

-- Estado completo da loja/pet numa só chamada (saldo sempre vindo do banco).
CREATE OR REPLACE FUNCTION public.obter_estado_loja(p_token text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE v_aluno bigint := public._aluno_da_sessao(p_token);
BEGIN
  RETURN jsonb_build_object(
    'xp',    (SELECT COALESCE(a.xp, 0) FROM public.alunos a WHERE a.id = v_aluno),
    'saldo', public._saldo_aluno(v_aluno),
    'comprados', COALESCE((SELECT jsonb_agg(i.acessorio_id ORDER BY i.acessorio_id)
                           FROM public.alunos_itens i WHERE i.aluno_id = v_aluno), '[]'::jsonb),
    'equipados', COALESCE((SELECT jsonb_agg(jsonb_build_object(
                             'pet_id', e.pet_id, 'slot', e.slot, 'acessorio_id', e.acessorio_id))
                           FROM public.alunos_equipados e WHERE e.aluno_id = v_aluno), '[]'::jsonb)
  );
END;
$$;

-- Compra atômica: trava a linha do aluno (serializa duplo clique, dois
-- dispositivos e o gatilho de XP das missões, que também faz UPDATE em alunos).
CREATE OR REPLACE FUNCTION public.comprar_acessorio(p_token text, p_acessorio_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_aluno bigint := public._aluno_da_sessao(p_token);
  v_item  public.acessorios%ROWTYPE;
  v_saldo bigint;
BEGIN
  PERFORM 1 FROM public.alunos WHERE id = v_aluno FOR UPDATE;

  SELECT * INTO v_item FROM public.acessorios WHERE id = p_acessorio_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'item_indisponivel' USING ERRCODE = '22023';
  END IF;

  -- Recompra é idempotente e vale mesmo se o ADM desativou o item depois (posse preservada).
  IF EXISTS (SELECT 1 FROM public.alunos_itens
             WHERE aluno_id = v_aluno AND acessorio_id = v_item.id) THEN
    RETURN jsonb_build_object('ja_possuia', true, 'cobrado', 0,
                              'saldo', public._saldo_aluno(v_aluno));
  END IF;

  IF NOT v_item.ativo OR v_item.slot NOT IN ('chapeu', 'colar', 'fundo') THEN
    RAISE EXCEPTION 'item_indisponivel' USING ERRCODE = '22023';
  END IF;

  v_saldo := public._saldo_aluno(v_aluno);
  IF v_saldo < v_item.preco THEN
    RAISE EXCEPTION 'saldo_insuficiente' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.alunos_itens (aluno_id, acessorio_id, preco_pago, origem)
  VALUES (v_aluno, v_item.id, v_item.preco, 'compra');

  RETURN jsonb_build_object('ja_possuia', false, 'cobrado', v_item.preco,
                            'saldo', v_saldo - v_item.preco);
END;
$$;

-- Equipar / trocar / desequipar (p_acessorio_id NULL = desequipar o slot).
CREATE OR REPLACE FUNCTION public.equipar_acessorio(
  p_token text, p_pet_id bigint, p_slot text, p_acessorio_id bigint
) RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE v_aluno bigint := public._aluno_da_sessao(p_token);
BEGIN
  IF p_slot IS NULL OR p_slot NOT IN ('chapeu', 'colar', 'fundo') THEN
    RAISE EXCEPTION 'slot_invalido' USING ERRCODE = '22023';
  END IF;

  IF p_acessorio_id IS NULL THEN
    DELETE FROM public.alunos_equipados
    WHERE aluno_id = v_aluno AND pet_id = p_pet_id AND slot = p_slot;
    RETURN;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.alunos_itens
                 WHERE aluno_id = v_aluno AND acessorio_id = p_acessorio_id) THEN
    RAISE EXCEPTION 'item_nao_comprado' USING ERRCODE = '22023';
  END IF;

  -- slot x catálogo e PET x turma do aluno são validados pelo gatilho
  INSERT INTO public.alunos_equipados (aluno_id, pet_id, slot, acessorio_id)
  VALUES (v_aluno, p_pet_id, p_slot, p_acessorio_id)
  ON CONFLICT (aluno_id, pet_id, slot)
  DO UPDATE SET acessorio_id = EXCLUDED.acessorio_id, atualizado_em = now();
END;
$$;

-- Migração do que já existe em localStorage/AsyncStorage (idempotente).
--   p_itens:     [14, 17, 20]                      (ids de itens_comprados_<aluno>)
--   p_equipados: [{"pet_id":5,"slot":"chapeu","acessorio_id":14}, ...]
-- Regras: ignora o que já está no servidor (a nuvem vence); só importa item
-- ativo; aplica o saldo — um dispositivo antigo nunca "cria moedas": se a soma
-- passar do saldo, os itens excedentes são devolvidos em `rejeitados`.
-- Pode ser chamada de novo por outro dispositivo (cada um paga com o mesmo XP,
-- então o saldo limita o conjunto total).
CREATE OR REPLACE FUNCTION public.importar_estado_local(
  p_token text, p_itens bigint[], p_equipados jsonb DEFAULT '[]'::jsonb
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_aluno bigint := public._aluno_da_sessao(p_token);
  v_item  public.acessorios%ROWTYPE;
  v_id    bigint;
  v_eq    jsonb;
  v_importados jsonb := '[]'::jsonb;
  v_rejeitados jsonb := '[]'::jsonb;
  v_eq_ok  integer := 0;
  v_eq_rej integer := 0;
BEGIN
  IF COALESCE(array_length(p_itens, 1), 0) > 200
     OR (jsonb_typeof(p_equipados) = 'array' AND jsonb_array_length(p_equipados) > 200) THEN
    RAISE EXCEPTION 'lista_grande_demais' USING ERRCODE = '22023';
  END IF;

  PERFORM 1 FROM public.alunos WHERE id = v_aluno FOR UPDATE;

  FOR v_id IN SELECT DISTINCT x FROM unnest(COALESCE(p_itens, ARRAY[]::bigint[])) AS x ORDER BY x LOOP
    SELECT * INTO v_item FROM public.acessorios WHERE id = v_id;
    IF NOT FOUND OR v_item.slot NOT IN ('chapeu', 'colar', 'fundo') THEN
      v_rejeitados := v_rejeitados || jsonb_build_object('id', v_id, 'motivo', 'item_indisponivel');
    ELSIF NOT v_item.ativo THEN   -- desativado pelo ADM depois da compra local: não importa, mas o local fica no backup
      v_rejeitados := v_rejeitados || jsonb_build_object('id', v_id, 'motivo', 'item_desativado');
    ELSIF EXISTS (SELECT 1 FROM public.alunos_itens WHERE aluno_id = v_aluno AND acessorio_id = v_id) THEN
      NULL;  -- já está na nuvem: não duplica nem cobra de novo
    ELSIF public._saldo_aluno(v_aluno) < v_item.preco THEN
      v_rejeitados := v_rejeitados || jsonb_build_object('id', v_id, 'motivo', 'saldo_insuficiente');
    ELSE
      INSERT INTO public.alunos_itens (aluno_id, acessorio_id, preco_pago, origem)
      VALUES (v_aluno, v_id, v_item.preco, 'importacao_local');
      v_importados := v_importados || to_jsonb(v_id);
    END IF;
  END LOOP;

  FOR v_eq IN SELECT * FROM jsonb_array_elements(
      CASE WHEN jsonb_typeof(p_equipados) = 'array' THEN p_equipados ELSE '[]'::jsonb END) LOOP
    BEGIN
      IF EXISTS (SELECT 1 FROM public.alunos_equipados
                 WHERE aluno_id = v_aluno
                   AND pet_id = (v_eq->>'pet_id')::bigint AND slot = v_eq->>'slot') THEN
        CONTINUE;  -- nuvem vence
      END IF;
      INSERT INTO public.alunos_equipados (aluno_id, pet_id, slot, acessorio_id)
      VALUES (v_aluno, (v_eq->>'pet_id')::bigint, v_eq->>'slot', (v_eq->>'acessorio_id')::bigint);
      v_eq_ok := v_eq_ok + 1;
    EXCEPTION WHEN OTHERS THEN   -- FK/CHECK/gatilho: descarta só esta linha
      v_eq_rej := v_eq_rej + 1;
    END;
  END LOOP;

  RETURN jsonb_build_object(
    'importados', v_importados, 'rejeitados', v_rejeitados,
    'equipados_importados', v_eq_ok, 'equipados_rejeitados', v_eq_rej,
    'saldo', public._saldo_aluno(v_aluno)
  );
END;
