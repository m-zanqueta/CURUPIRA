-- =============================================================================
-- PROPOSTA — NÃO EXECUTAR EM PRODUÇÃO SEM REVISÃO DA EQUIPE (Matheus = banco).
-- Persistência em nuvem do inventário e dos acessórios equipados por aluno.
--
-- Premissas verificadas nas migrations do repositório (PR #31):
--   * alunos.id, turmas.id e pets.id são bigint (alunos_missoes os referencia
--     como bigint). A coluna de turma em alunos é "turmaId" (camelCase, entre
--     aspas). O tipo de acessorios.id NÃO aparece nas migrations — confirme
--     com o pré-check do arquivo PROPOSTA (FK bigint -> int4 também funciona).
--   * O app NÃO usa Supabase Auth: o login é feito direto em public.alunos
--     (e-mail + senha), então auth.uid() é NULL e NÃO identifica alunos.
--     Por isso a identidade vem de um token de sessão emitido por RPC.
--   * Padrão do projeto: tabela sem acesso direto + RPC SECURITY DEFINER
--     (ver public.coordenadores / login_coordenador).
--
-- A migration é ADITIVA: cria tabelas/funções novas e UM gatilho em public.alunos
-- (alunos_sincroniza_credencial). NÃO altera colunas de public.alunos, não remove,
-- não renomeia e não desliga nada. Não toca em
-- public.pets_acessorios_equipados (é por PET = turma inteira; fica intocada).
-- =============================================================================

-- Tudo numa transação: se qualquer comando falhar, nada fica aplicado pela metade.
BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;

-- -----------------------------------------------------------------------------
-- 0) Credenciais (hash bcrypt com salt, custo 10) em tabela SEPARADA e trancada.
--    O hash NÃO fica em public.alunos: hoje a chave anon lê `alunos` inteira
--    (select('*')), e o hash ficaria exposto junto. Aqui ele é inacessível ao app.
--    * O login usa o hash quando existe; senão compara a senha em texto puro
--      (transição) e cria o hash no 1º login bem-sucedido.
--    * O gatilho abaixo mantém o hash em sincronia quando `alunos.senha` é
--      inserida/alterada por outro caminho (cadastro, painel ADM). Sem ele, uma
--      troca de senha pelo ADM deixaria o hash antigo valendo.
--    * A coluna `senha` em texto puro NÃO é apagada por esta migration (não há
--      como fazê-lo sem antes trocar cadastro/ADM/login legado). O passo seguro
--      e reversível está em FASE2_credenciais_sem_texto_puro.sql (manual).
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.alunos_credenciais (
  aluno_id      bigint PRIMARY KEY REFERENCES public.alunos(id) ON DELETE CASCADE,
  senha_hash    text   NOT NULL,
  atualizado_em timestamptz NOT NULL DEFAULT now()
);

-- -----------------------------------------------------------------------------
-- 1) Sessões do aluno (token opaco; só o hash SHA-256 fica no banco)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.alunos_sessoes (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aluno_id    bigint NOT NULL REFERENCES public.alunos(id) ON DELETE CASCADE,
  token_hash  bytea  NOT NULL UNIQUE,
  criado_em   timestamptz NOT NULL DEFAULT now(),
  expira_em   timestamptz NOT NULL DEFAULT now() + interval '30 days',
  revogado_em timestamptz
);
CREATE INDEX IF NOT EXISTS alunos_sessoes_aluno_idx ON public.alunos_sessoes (aluno_id);

-- Tentativas de login malsucedidas (limite por e-mail; ver login_aluno).
CREATE TABLE IF NOT EXISTS public.alunos_login_falhas (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email      text NOT NULL,
  ip         text,
  ocorrido_em timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.alunos_login_falhas ADD COLUMN IF NOT EXISTS ip text;
CREATE INDEX IF NOT EXISTS alunos_login_falhas_idx ON public.alunos_login_falhas (email, ocorrido_em);
CREATE INDEX IF NOT EXISTS alunos_login_falhas_ip_idx ON public.alunos_login_falhas (ip, ocorrido_em);

-- -----------------------------------------------------------------------------
-- 2) Inventário oficial por aluno (catálogo `acessorios` continua separado)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.alunos_itens (
  aluno_id     bigint NOT NULL REFERENCES public.alunos(id) ON DELETE CASCADE,
  acessorio_id bigint NOT NULL REFERENCES public.acessorios(id) ON DELETE RESTRICT,
  preco_pago   integer NOT NULL CHECK (preco_pago >= 0),   -- preço congelado na compra
  origem       text NOT NULL DEFAULT 'compra'
               CHECK (origem IN ('compra', 'importacao_local')),
  comprado_em  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (aluno_id, acessorio_id)                      -- impede compra duplicada
);

-- -----------------------------------------------------------------------------
-- 3) Acessórios equipados por aluno + PET + slot
--    Desequipar = apagar a linha. A FK composta garante que só se equipa o
--    que está no inventário do próprio aluno (e remove o equipado se o item
--    sair do inventário).
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.alunos_equipados (
  aluno_id      bigint NOT NULL,
  pet_id        bigint NOT NULL REFERENCES public.pets(id) ON DELETE CASCADE,
  slot          text   NOT NULL CHECK (slot IN ('chapeu', 'colar', 'fundo')),
  acessorio_id  bigint NOT NULL,
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (aluno_id, pet_id, slot),
  FOREIGN KEY (aluno_id, acessorio_id)
    REFERENCES public.alunos_itens (aluno_id, acessorio_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS alunos_equipados_pet_idx ON public.alunos_equipados (pet_id);

-- Regras que FK/CHECK não cobrem: o slot da linha tem de ser o slot do item
-- no catálogo, e o PET tem de ser o da turma atual do aluno.
CREATE OR REPLACE FUNCTION public.validar_aluno_equipado()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.acessorios a
    WHERE a.id = NEW.acessorio_id AND a.slot = NEW.slot
  ) THEN
    RAISE EXCEPTION 'slot_incompativel' USING ERRCODE = '22023';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.alunos al
    JOIN public.pets p ON p.turma_id = al."turmaId"
    WHERE al.id = NEW.aluno_id AND p.id = NEW.pet_id
  ) THEN
    RAISE EXCEPTION 'pet_fora_da_turma_do_aluno' USING ERRCODE = '22023';
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.validar_aluno_equipado() FROM PUBLIC, anon, authenticated;  -- função de gatilho: não é RPC
DROP TRIGGER IF EXISTS alunos_equipados_validar ON public.alunos_equipados;
CREATE TRIGGER alunos_equipados_validar
BEFORE INSERT OR UPDATE ON public.alunos_equipados
FOR EACH ROW EXECUTE FUNCTION public.validar_aluno_equipado();

-- -----------------------------------------------------------------------------
-- 4) Segurança das tabelas: RLS ligado, SEM policies e SEM grants => o app
--    (anon/authenticated) não lê nem escreve nada direto. Só as RPCs abaixo.
-- -----------------------------------------------------------------------------
ALTER TABLE public.alunos_credenciais ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.alunos_login_falhas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.alunos_sessoes   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.alunos_itens     ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.alunos_equipados ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.alunos_sessoes, public.alunos_itens, public.alunos_equipados,
  public.alunos_login_falhas, public.alunos_credenciais FROM PUBLIC, anon, authenticated;

-- Gatilho: mantém alunos_credenciais em sincronia com alunos.senha.
--  * ignora senha nula/vazia (nunca cria hash de senha vazia);
--  * se o hash falhar, APAGA a credencial (o login cai no texto puro, correto) e
--    segue — o cadastro/painel ADM nunca é bloqueado por esta migration;
--  * não registra a senha em nenhuma mensagem.
CREATE OR REPLACE FUNCTION public.sincronizar_credencial_aluno()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF NEW.senha IS NULL OR NEW.senha = '' THEN RETURN NULL; END IF;
  IF TG_OP = 'UPDATE' AND OLD.senha IS NOT DISTINCT FROM NEW.senha THEN RETURN NULL; END IF;
  IF TG_OP = 'UPDATE' THEN   -- senha trocada: derruba as sessões abertas (token antigo deixa de valer)
    UPDATE public.alunos_sessoes SET revogado_em = now() WHERE aluno_id = NEW.id AND revogado_em IS NULL;
  END IF;
  BEGIN
    INSERT INTO public.alunos_credenciais (aluno_id, senha_hash)
    VALUES (NEW.id, extensions.crypt(NEW.senha, extensions.gen_salt('bf', 10)))
    ON CONFLICT (aluno_id) DO UPDATE
      SET senha_hash = EXCLUDED.senha_hash, atualizado_em = now();
  EXCEPTION WHEN OTHERS THEN
    DELETE FROM public.alunos_credenciais WHERE aluno_id = NEW.id;
    RAISE WARNING 'credencial do aluno % nao sincronizada (sqlstate %)', NEW.id, SQLSTATE;
  END;
  RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION public.sincronizar_credencial_aluno() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS alunos_sincroniza_credencial ON public.alunos;
CREATE TRIGGER alunos_sincroniza_credencial
AFTER INSERT OR UPDATE OF senha ON public.alunos
FOR EACH ROW EXECUTE FUNCTION public.sincronizar_credencial_aluno();

